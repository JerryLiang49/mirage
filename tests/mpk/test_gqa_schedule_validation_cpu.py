"""Validate actual compiler schedules against GQA runtime wait dependencies."""

def test_live_graph_schedule_validation(tmp_path):
    import json, pathlib, sys
    from mirage.core import CyKNGraph, bfloat16, int32
    from mirage.kernel import KNGraph
    from mirage.mpk.static_megakernel import StaticMegakernel
    from mirage.mpk import compiler, static_schedule

    pk = StaticMegakernel.__new__(StaticMegakernel)
    pk.__finalized__ = True  # no real constructor or runtime to finalize
    pk.kn_graph = KNGraph(CyKNGraph(disable_fingerprint=True))
    pk.num_gpus, pk.num_sms, pk.tokens = 1, 128, 8
    pk._static_nodes, pk._bufs, pk._maps, pk._counter_lines = {}, [], [], 0
    pk._tensor_names, pk._model_tensors, pk._prefetch = {}, {}, []
    q=pk.new_tensor((8,8,8,128),dtype=bfloat16,name='query')
    k=pk.new_tensor((1032,64,8,128),dtype=bfloat16,name='keys')
    v=pk.new_tensor((1032,64,8,128),dtype=bfloat16,name='values')
    pages=pk.new_tensor((8,129),dtype=int32,name='pages')
    lengths=pk.new_tensor((8,),dtype=int32,name='lengths')
    windows=pk.new_tensor((8,),dtype=int32,name='windows')
    nk=pk.new_tensor((8,8,128),dtype=bfloat16,name='new_keys')
    nv=pk.new_tensor((8,8,128),dtype=bfloat16,name='new_values')
    out=pk.new_tensor((8,8192),dtype=bfloat16,name='output')
    sinks=pk.new_tensor((8,8),dtype=bfloat16,name='sinks')
    pk.paged_gqa_decode_layer(q,k,v,pages,lengths,windows,nk,nv,out,sinks,partition_tokens=4160,implementation='sm100')
    nodes=compiler.graph_nodes(pk)
    print('registered', [(n.graph_idx,n.name,n.grid,n.params) for n in nodes],flush=True)
    assert len(nodes)==2

    # Fresh deterministic placement, no measured costs or historical placement.
    import itertools
    producer,merge = nodes
    queues=[[] for _ in range(pk.num_sms)]
    producer_positions=list(itertools.product(*(range(x) for x in producer.grid)))
    merge_positions=list(itertools.product(*(range(x) for x in merge.grid)))
    assert len(producer_positions)==128 and len(merge_positions)==64
    for i,pos in enumerate(producer_positions):
        queues[(73*i+19)%128].append((producer.graph_idx,pos))
    for i,pos in enumerate(merge_positions):
        queues[(37*i+11)%128].append((merge.graph_idx,pos))
    # Stronger than the compiler's data-slice dependencies for this kernel:
    # every SM executes one producer before its optional merge. The merge waits
    # for all request/partition producers in its group, not just its own slice.
    assert all(queue and queue[0][0] == producer.graph_idx for queue in queues)
    assert sum(len(q) for q in queues)==192
    plan={'grids':{},'lists':[queues]}
    paths,info=compiler.compile_plan(pk,plan,str(tmp_path))
    fresh=json.loads(pathlib.Path(paths[0]).read_text())
    assert fresh['nodes']==compiler.node_table(nodes)
    assert len(fresh['all_tasks'])==192 and len(fresh['worker_task_queues'])==128
    # Exercise actual compile_plan output and reject corruptions before generation.
    import copy
    static_schedule.validate_gqa_schedule(pk,[fresh])
    # Actual merge wait is for K partitions x all eight requests of its group.
    for task in fresh['all_tasks']:
     if task['node']==merge.graph_idx:
      dependencies=[fresh['all_tasks'][i] for i in task['deps']]
      assert len(dependencies)==16 and all(x['node']==producer.graph_idx and x['pos'][0]==task['pos'][0] for x in dependencies)
      assert {(x['pos'][1],x['pos'][2]) for x in dependencies}=={(k,r) for k in range(2) for r in range(8)}
    for mode in ('stale_param','missing_dep','merge_before_producer','invalid_gpu','duplicate_task','negative_task'):
     bad=copy.deepcopy(fresh)
     if mode=='stale_param': bad['nodes'][str(producer.graph_idx)]['params'][0]+=1
     elif mode=='missing_dep': next(t for t in bad['all_tasks'] if t['node']==merge.graph_idx)['deps'].pop()
     elif mode=='invalid_gpu': bad['info']['gpu']=1
     elif mode=='duplicate_task': bad['worker_task_queues'][0].append(bad['worker_task_queues'][1][0])
     elif mode=='negative_task': bad['worker_task_queues'][0][0]=-1
     else:
      tasks=bad['all_tasks'];mid=next(i for i,t in enumerate(tasks) if t['node']==merge.graph_idx);pid=tasks[mid]['deps'][0]
      old=next(q for q in bad['worker_task_queues'] if mid in q);old.remove(mid)
      dest=next(q for q in bad['worker_task_queues'] if pid in q);dest.insert(dest.index(pid),mid)
     try: static_schedule.validate_gqa_schedule(pk,[bad])
     except ValueError: print('rejected',mode,flush=True)
     else: raise AssertionError('accepted '+mode)
    code=static_schedule.generate_code(pk,[fresh],cooperative_gqa=True)
    assert 'run_gqa_paged_parts' in code and 'run_gqa_merge_ready' in code
    pathlib.Path(str(tmp_path / "layer.cu")).write_text(code)
    print('compiled fresh deterministic placement:',len(producer_positions),'producers,',len(merge_positions),'merges; generated bytes',len(code),flush=True)
